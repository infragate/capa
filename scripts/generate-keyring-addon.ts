#!/usr/bin/env bun
/**
 * Generate src/shared/keyring-addon.ts with a static require of the
 * @napi-rs/keyring platform package for the build target.
 *
 * @napi-rs/keyring picks its native addon with a dynamic require at runtime,
 * which `bun build --compile` can't follow, so the .node file never gets
 * embedded. A static require of the target's package does get embedded.
 *
 * Target: BUN_TARGET env (e.g. bun-linux-arm64, bun-linux-x64-musl,
 * bun-windows-x64), else the host. When cross-compiling, install the target's
 * optional deps first, e.g. `bun install --os=linux --cpu=arm64`.
 */

import { writeFileSync } from 'fs';
import { join } from 'path';

function hostIsMusl(): boolean {
  const report = process.report?.getReport() as { header?: { glibcVersionRuntime?: string } } | undefined;
  return !report?.header?.glibcVersionRuntime;
}

function addonPackage(): string {
  const target = process.env.BUN_TARGET;
  const [, os, arch, ...mods] = target ? target.split('-') : ['bun', process.platform, process.arch];
  const platform = os === 'windows' ? 'win32' : os;
  if (platform === 'win32') return `@napi-rs/keyring-win32-${arch}-msvc`;
  if (platform === 'darwin') return `@napi-rs/keyring-darwin-${arch}`;
  if (platform === 'linux') {
    const musl = target ? mods.includes('musl') : hostIsMusl();
    return `@napi-rs/keyring-linux-${arch}-${musl ? 'musl' : 'gnu'}`;
  }
  throw new Error(`Unsupported keyring target: ${target ?? `${process.platform}-${process.arch}`}`);
}

const pkg = addonPackage();
try {
  require.resolve(pkg);
} catch {
  console.error(`✗ ${pkg} is not installed. Install the target's optional deps, e.g. \`bun install --os=<os> --cpu=<cpu>\`.`);
  process.exit(1);
}

const outputPath = join(process.cwd(), 'src', 'shared', 'keyring-addon.ts');
writeFileSync(
  outputPath,
  `/**
 * Auto-generated file - DO NOT EDIT
 * Generated by scripts/generate-keyring-addon.ts
 * Static require so \`bun build --compile\` embeds the native keyring addon.
 */

export default require('${pkg}');
`,
  'utf-8',
);
console.log(`✓ Generated ${outputPath} (${pkg})`);
